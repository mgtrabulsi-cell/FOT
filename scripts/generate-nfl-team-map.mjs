// Regenerates supabase/functions/_shared/nflTeamMap.ts by matching the ESPN and
// API-Sports NFL team directories on normalized franchise names.
// Usage: API_SPORTS_KEY=<key> node scripts/generate-nfl-team-map.mjs
import { writeFileSync } from 'node:fs';

const key = process.env.API_SPORTS_KEY;
if (!key) throw new Error('Set API_SPORTS_KEY in the environment before regenerating the map.');

const normalize = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

const espnPayload = await (await fetch('https://site.api.espn.com/apis/site/v2/sports/football/nfl/teams?limit=32')).json();
const espnTeams = (espnPayload.sports?.[0]?.leagues?.[0]?.teams ?? []).map((entry) => entry.team)
  .filter((team) => team?.id && team.displayName);
if (espnTeams.length !== 32) throw new Error(`ESPN returned ${espnTeams.length} teams instead of 32.`);

const apiPayload = await (await fetch('https://v1.american-football.api-sports.io/teams?league=1&season=' + new Date().getFullYear(), {
  headers: { 'x-apisports-key': key },
})).json();
const apiTeams = (apiPayload.response ?? []).filter((team) => team?.id && team.name);
if (apiTeams.length !== 32) throw new Error(`API-Sports returned ${apiTeams.length} teams instead of 32 (errors: ${JSON.stringify(apiPayload.errors)}).`);

const byName = new Map(apiTeams.map((team) => [normalize(team.name), team]));
const rows = espnTeams.map((team) => {
  const match = byName.get(normalize(team.displayName));
  if (!match) throw new Error(`No API-Sports match for ESPN team "${team.displayName}".`);
  return { espnId: String(team.id), apiSportsId: String(match.id), name: team.displayName, espnAbbr: team.abbreviation, apiSportsCode: match.code };
}).sort((first, second) => Number(first.apiSportsId) - Number(second.apiSportsId));

const source = `// Generated by scripts/generate-nfl-team-map.mjs — do not edit by hand.
// Bridges ESPN team IDs (used across favorites, box scores and the bot) to API-Sports NFL team IDs.

export type NFLTeamMapping = { espnId: string; apiSportsId: string; name: string; espnAbbr: string; apiSportsCode: string };

export const nflTeamMap: NFLTeamMapping[] = ${JSON.stringify(rows, null, 2).replace(/"([a-zA-Z]+)":/g, '$1:')};

export const nflTeamByESPNId = new Map(nflTeamMap.map((team) => [team.espnId, team]));
export const nflTeamByAPISportsId = new Map(nflTeamMap.map((team) => [team.apiSportsId, team]));
`;
writeFileSync('supabase/functions/_shared/nflTeamMap.ts', source, 'utf8');
console.log(`Wrote ${rows.length} team mappings to supabase/functions/_shared/nflTeamMap.ts`);
